import { prepareExportBundle } from "@/lib/export-bundle";

export type VfsFiles = Record<string, string>;

const toBase64 = (content: string) =>
  btoa(
    encodeURIComponent(content).replace(/%([0-9A-F]{2})/g, (_, p1) =>
      String.fromCharCode(parseInt(p1, 16))
    )
  );

async function putFile(
  token: string,
  username: string,
  repoName: string,
  path: string,
  content: string,
  message: string
) {
  const fileRes = await fetch(
    `https://api.github.com/repos/${username}/${repoName}/contents/${path}`,
    { headers: { Authorization: `Bearer ${token}` } }
  );

  let sha: string | undefined;
  if (fileRes.ok) {
    const fileData = await fileRes.json();
    sha = fileData.sha;
  }

  const putRes = await fetch(
    `https://api.github.com/repos/${username}/${repoName}/contents/${path}`,
    {
      method: "PUT",
      headers: {
        Authorization: `Bearer ${token}`,
        "Content-Type": "application/json",
      },
      body: JSON.stringify({
        message,
        content: toBase64(content),
        ...(sha ? { sha } : {}),
      }),
    }
  );

  if (!putRes.ok) {
    const errorData = await putRes.json().catch(() => ({}));
    if (putRes.status === 404) {
      throw new Error(
        `Repository '${repoName}' not found. Creation may still be initializing.`
      );
    }
    throw new Error(errorData.message || `Failed to push ${path}`);
  }
}

/** Push an entire VFS (multifile) to a new or existing GitHub repo */
export const pushVfsToGitHub = async (
  token: string,
  repoName: string,
  files: VfsFiles,
  message: string = "ShipKernel multifile export"
) => {
  const userRes = await fetch("https://api.github.com/user", {
    headers: { Authorization: `Bearer ${token}` },
  });
  const userData = await userRes.json();
  const username = userData.login;
  if (!username) throw new Error("Could not resolve GitHub user from token.");

  const createRepoRes = await fetch("https://api.github.com/user/repos", {
    method: "POST",
    headers: {
      Authorization: `Bearer ${token}`,
      "Content-Type": "application/json",
    },
    body: JSON.stringify({
      name: repoName,
      description: "Generated by ShipKernel",
      auto_init: true,
    }),
  });

  if (!createRepoRes.ok && createRepoRes.status !== 422) {
    if (createRepoRes.status === 404) {
      throw new Error(
        "GitHub 'repo' scope is missing. Reconnect GitHub with repo permissions."
      );
    }
    if (createRepoRes.status === 403) {
      throw new Error("Insufficient GitHub permissions to create repositories.");
    }
    const errorData = await createRepoRes.json().catch(() => ({}));
    throw new Error(errorData.message || "Failed to create repository");
  }

  // Give auto_init a moment on brand-new repos
  await new Promise((r) => setTimeout(r, 800));

  const bundled = prepareExportBundle(files, { projectName: repoName });
  const entries = Object.entries(bundled);
  if (entries.length === 0) throw new Error("No files to push.");

  for (const [path, content] of entries) {
    await putFile(token, username, repoName, path, content, message);
  }

  return {
    url: `https://github.com/${username}/${repoName}`,
    username,
    fileCount: entries.length,
  };
};

/** @deprecated Prefer pushVfsToGitHub */
export const pushToGitHub = async (
  token: string,
  repoName: string,
  fileName: string,
  content: string,
  message?: string
) => pushVfsToGitHub(token, repoName, { [fileName]: content }, message);
