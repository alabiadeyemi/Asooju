export const pushToGitHub = async (
    token: string,
    repoName: string,
    fileName: string,
    content: string,
    message: string = "Automated deploy from ShipKernel"
) => {
    try {
        // 1. Get user info to get username
        const userRes = await fetch("https://api.github.com/user", {
            headers: { Authorization: `Bearer ${token}` },
        });
        const userData = await userRes.json();
        const username = userData.login;

        // 2. Try to create the repo (it might already exist)
        const createRepoRes = await fetch("https://api.github.com/user/repos", {
            method: "POST",
            headers: {
                Authorization: `Bearer ${token}`,
                "Content-Type": "application/json",
            },
            body: JSON.stringify({
                name: repoName,
                description: "Architecture blueprint generated by ShipKernel AI",
                auto_init: true,
            }),
        });

        // If repo creation fails and it's not because it already exists (422), we should know
        if (!createRepoRes.ok && createRepoRes.status !== 422) {
            const errorData = await createRepoRes.json().catch(() => ({}));
            console.error("Repo Creation Failed:", errorData);

            // If we get a 404 here, it's almost certainly a missing scope issue
            if (createRepoRes.status === 404) {
                throw new Error("GitHub 'repo' scope is missing. Please disconnect and reconnect your GitHub account to grant permissions.");
            }

            // If we get a 403, it might be an organization or rate limit issue
            if (createRepoRes.status === 403) {
                throw new Error("Insufficient GitHub permissions. Please ensure your token allows repository creation.");
            }
        }

        // 3. Create or Update file
        // First, try to get the file SHA if it exists (for updates)
        const fileRes = await fetch(
            `https://api.github.com/repos/${username}/${repoName}/contents/${fileName}`,
            {
                headers: { Authorization: `Bearer ${token}` },
            }
        );

        let sha = null;
        if (fileRes.ok) {
            const fileData = await fileRes.json();
            sha = fileData.sha;
        }

        const putRes = await fetch(
            `https://api.github.com/repos/${username}/${repoName}/contents/${fileName}`,
            {
                method: "PUT",
                headers: {
                    Authorization: `Bearer ${token}`,
                    "Content-Type": "application/json",
                },
                body: JSON.stringify({
                    message,
                    content: btoa(encodeURIComponent(content).replace(/%([0-9A-F]{2})/g, (_, p1) => String.fromCharCode(parseInt(p1, 16)))), // Robust Unicode-safe Base64 encode
                    sha: sha // Include SHA if updating
                }),
            }
        );

        if (!putRes.ok) {
            const errorData = await putRes.json().catch(() => ({}));

            // Handle common push errors
            if (putRes.status === 404) {
                throw new Error(`Repository '${repoName}' not found. It might take a moment for GitHub to initialize it, or creation may have failed.`);
            }

            throw new Error(errorData.message || "Failed to push file to GitHub");
        }

        return {
            url: `https://github.com/${username}/${repoName}`,
            username
        };
    } catch (error: any) {
        console.error("GitHub Service Error:", error);
        throw error;
    }
};
